function insertImageToMarkdown(url, caption = '') {
  const textarea = document.getElementById('markdown_content');
  if (!textarea) return;

  const markdownImage = `\n\n![${caption.replace(/[\n\r]/g, ' ').substring(0, 80)}](${url})\n*Photo reconstruction of ${caption.substring(0, 60)}.*\n\n`;

  const start = textarea.selectionStart;
  const end = textarea.selectionEnd;
  const val = textarea.value;

  textarea.value = val.substring(0, start) + markdownImage + val.substring(end);
  textarea.selectionStart = textarea.selectionEnd = start + markdownImage.length;
  textarea.focus();

  updateWordCount();
  updateLivePreview();
  showToast('Inserted image into article body!', 'success');
}

