  if (writerList) {
    writerList.innerHTML = currentImagePrompts.map((p, i) => createPromptCard(p, i, true)).join('');
  }

  // 3. Render in Modal
  if (modalList) {
    modalList.innerHTML = currentImagePrompts.map((p, i) => createPromptCard(p, i, false)).join('');
  }
