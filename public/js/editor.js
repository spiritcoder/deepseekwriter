function downloadArticleMarkdown() {
  const textarea = document.getElementById('markdown_content');
  const titleField = document.getElementById('article_title');
  if (!textarea || !textarea.value) {
    showToast('No content to download', 'error');
    return;
  }

  const title = (titleField?.value || 'igboatlas-article').replace(/[^a-z0-9_-]/gi, '-');
  const blob = new Blob([textarea.value], { type: 'text/markdown;charset=utf-8;' });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = `${title}.md`;
  a.click();
  URL.revokeObjectURL(a);
  showToast('Downloaded .md file!', 'success');
}

function escapeHtml(str) {
  if (!str) return '';
  return String(str)
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#039;');
}

