async function handleModalImageUpload(event) {
  const file = event.target.files && event.target.files[0];
  if (!file) return;
  uploadImageFile(file);
}

function handleModalDropUpload(event) {
  event.preventDefault();
  const file = event.dataTransfer.files && event.dataTransfer.files[0];
  if (!file) return;
  uploadImageFile(file);
}

async function uploadImageFile(file) {
  showToast('Uploading image...', 'info');
  const formData = new FormData();
  formData.append('image', file);

  try {
    const res = await fetch('/api/upload-image', {
      method: 'POST',
      body: formData
    });
    const data = await res.json();
    if (!data.success) throw new Error(data.error);

    const img = data.image;
    insertImageToMarkdown(img.url, file.name.replace(/\.[^.]+$/, ''));
    if (!currentCoverImage) {
      setAsCoverImage(img.url);
    }
    showToast('Image uploaded and inserted into article!', 'success');
    closeModal('modal-insert-image');
  } catch (err) {
    showToast('Upload failed: ' + err.message, 'error');
  }
}

