async function generateArticleWithDeepSeek() {
  const topic = document.getElementById('article_topic').value.trim();
  const region = document.getElementById('article_region').value.trim();
  const customAngle = document.getElementById('article_angle').value.trim();
  const includeSummary = document.getElementById('toggle_summary').checked;
  const includeReferences = document.getElementById('toggle_references').checked;
  const modelSelect = document.getElementById('deepseek_model_select');
  const model = modelSelect ? modelSelect.value : 'deepseek-chat';
  const minWordsSelect = document.getElementById('article_min_words');
  const minWords = minWordsSelect ? (parseInt(minWordsSelect.value) || 1500) : 1500;
  const btn = document.getElementById('btn-generate-article');

  if (!topic) {
    showToast('Please enter an Article Topic first', 'error');
    document.getElementById('article_topic').focus();
    return;
  }

  const originalText = btn.innerHTML;
  btn.disabled = true;
  btn.innerHTML = `<span class="spinner"></span> Generating with DeepSeek (~${minWords} words)...`;

  showToast(`DeepSeek (${model}) is writing your ~${minWords}-word article...`, 'info');

  try {
    const res = await fetch('/api/generate', {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({
        topic,
        region,
        customAngle,
        outline: currentOutline,
        includeSummary,
        includeReferences,
        searchResults: currentSearchResults,
        minWords,
        model
      })
    });

    const data = await res.json();
    if (!data.success) throw new Error(data.error);

    // Populate editor fields
    const markdownField = document.getElementById('markdown_content');
    const summaryField = document.getElementById('executive_summary');
    const titleField = document.getElementById('article_title');

    if (data.articleBody) {
      markdownField.value = data.articleBody;
    }
    if (data.summary) {
      summaryField.value = data.summary;
    }

    // Auto extract H1 title if title is empty or placeholder
    if (!titleField.value || titleField.value.trim() === 'Untitled Draft') {
      const h1Match = data.articleBody.match(/^#\s+(.+)$/m);
      if (h1Match && h1Match[1]) {
        titleField.value = h1Match[1].replace(/\[|\]/g, '').trim();
      } else {
        titleField.value = topic;
      }
    }

    // Save suggested image prompts
    if (Array.isArray(data.imagePrompts) && data.imagePrompts.length > 0) {
      currentImagePrompts = data.imagePrompts;
      renderImagePrompts();
    }

    // Immediately populate the Flux prompt with the generated prompt or derived title
    ensureFluxPromptPopulated(true);

    // Save reasoning log
    if (data.reasoningContent) {
      currentReasoning = data.reasoningContent;
      renderReasoningUI();
    }

    updateWordCount();
    updateLivePreview();
    showToast('Full article generated successfully!', 'success');

    // Switch view to preview
    const previewContainer = document.querySelector('.preview-pane');
    if (previewContainer) {
      previewContainer.scrollTop = 0;
    }
  } catch (err) {
    showToast('Generation failed: ' + err.message, 'error');
  } finally {
    btn.disabled = false;
    btn.innerHTML = originalText;
  }
}

function renderReasoningUI() {
  const container = document.getElementById('reasoning-display');
  if (!container || !currentReasoning) return;
  container.style.display = 'block';
  const textElem = document.getElementById('reasoning-text');
  if (textElem) {
    textElem.innerText = currentReasoning;
  }
}

