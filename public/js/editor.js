async function runWebResearch() {
  const topic = document.getElementById('article_topic').value.trim();
  const region = document.getElementById('article_region').value.trim();
  const customQuery = document.getElementById('research_query').value.trim();
  const btn = document.getElementById('btn-run-research');

  if (!topic && !customQuery) {
    showToast('Please enter a Topic or Search Query first', 'error');
    return;
  }

  const originalText = btn.innerHTML;
  btn.disabled = true;
  btn.innerHTML = `<span class="spinner"></span> Searching Web...`;

  try {
    const res = await fetch('/api/research', {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({
        topic,
        region,
        customQuery: customQuery || undefined,
        count: 5
      })
    });
    const data = await res.json();
    if (!data.success) throw new Error(data.error);

    currentSearchResults = data.results || [];
    renderResearchResults();
    showToast(`Discovered ${currentSearchResults.length} live research references!`, 'success');
  } catch (err) {
    showToast('Research error: ' + err.message, 'error');
  } finally {
    btn.disabled = false;
    btn.innerHTML = originalText;
  }
}

function renderResearchResults() {
  const container = document.getElementById('research-results-container');
  if (!container) return;

  if (currentSearchResults.length === 0) {
    container.innerHTML = `<div style="font-size: 0.78rem; color: var(--text-muted); text-align: center; padding: 12px;">No research queries run yet.</div>`;
    return;
  }

  let html = '';
  currentSearchResults.forEach((r, idx) => {
    html += `
      <div class="research-card">
        <div style="display: flex; justify-content: space-between; align-items: flex-start; gap: 6px;">
          <a href="${escapeHtml(r.url)}" target="_blank" class="research-card-title">${escapeHtml(r.title)}</a>
          <button type="button" class="btn btn-ghost btn-sm" onclick="removeResearchItem(${idx})" style="padding: 0 4px; font-size: 0.7rem; color: var(--text-muted);">✕</button>
        </div>
        <p class="research-card-snippet">${escapeHtml(r.snippet || r.summary || '')}</p>
      </div>
    `;
  });
  container.innerHTML = html;
}

function removeResearchItem(idx) {
  currentSearchResults.splice(idx, 1);
  renderResearchResults();
}

