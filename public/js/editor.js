function insertMarkdownSyntax(prefix, suffix = '') {
  const textarea = document.getElementById('markdown_content');
  if (!textarea) return;

  const start = textarea.selectionStart;
  const end = textarea.selectionEnd;
  const val = textarea.value;
  const selectedText = val.substring(start, end) || 'text';

  const replacement = `${prefix}${selectedText}${suffix}`;
  textarea.value = val.substring(0, start) + replacement + val.substring(end);
  textarea.selectionStart = start + prefix.length;
  textarea.selectionEnd = start + prefix.length + selectedText.length;
  textarea.focus();

  updateWordCount();
  updateLivePreview();
}

function updateWordCount() {
  const textarea = document.getElementById('markdown_content');
  const countElem = document.getElementById('word-count-display');
  const timeElem = document.getElementById('reading-time-display');
  if (!textarea || !countElem) return;

  const text = textarea.value.trim();
  const words = text ? text.split(/\s+/).filter(Boolean).length : 0;
  const readingTime = Math.max(1, Math.round(words / 200));

  countElem.innerText = `${words.toLocaleString()} words`;
  if (timeElem) {
    timeElem.innerText = `${readingTime} min read`;
  }
}

async function updateLivePreview() {
  const textarea = document.getElementById('markdown_content');
  const summaryArea = document.getElementById('executive_summary');
  const previewArea = document.getElementById('live-preview-content');
  const heroBanner = document.getElementById('preview-hero-banner');
  if (!textarea || !previewArea) return;

  const markdown = textarea.value;
  const summary = summaryArea ? summaryArea.value.trim() : '';

  // Update Hero Banner image
  if (heroBanner) {
    if (currentCoverImage) {
      heroBanner.style.display = 'block';
      heroBanner.querySelector('img').src = currentCoverImage;
    } else {
      heroBanner.style.display = 'none';
    }
  }

  // Update Executive Summary Preview
  const summaryBox = document.getElementById('preview-summary-box');
  if (summaryBox) {
    if (summary) {
      summaryBox.style.display = 'block';
      document.getElementById('preview-summary-text').innerHTML = summary.replace(/\n/g, '<br>');
    } else {
      summaryBox.style.display = 'none';
    }
  }

  if (!markdown.trim()) {
    previewArea.innerHTML = `<p style="color: var(--text-muted); font-style: italic;">Live rendered article will appear here as you write or generate...</p>`;
    return;
  }

  try {
    const res = await fetch('/api/render-markdown', {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({ markdown })
    });
    const data = await res.json();
    if (data.success) {
      previewArea.innerHTML = data.html;
    }
  } catch (err) {
    console.error('Failed to render markdown live:', err);
  }
}

