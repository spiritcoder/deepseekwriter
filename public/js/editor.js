function renderOutlineBuilder() {
  const container = document.getElementById('outline-builder-container');
  if (!container) return;

  if (currentOutline.length === 0) {
    container.innerHTML = `
      <div style="font-size: 0.8rem; color: var(--text-muted); text-align: center; padding: 12px; border: 1px dashed var(--border-color); border-radius: 6px;">
        No custom outline yet. DeepSeek Flash will automatically organize sections, or click "Add Section" below.
      </div>
    `;
    return;
  }

  let html = '';
  currentOutline.forEach((item, index) => {
    html += `
      <div class="outline-item" data-index="${index}">
        <div class="outline-item-header">
          <span style="font-size: 0.75rem; color: var(--text-muted); font-weight: 700;">H2</span>
          <input type="text" class="outline-item-title-input" value="${escapeHtml(item.title || '')}" placeholder="Section Title (e.g., Sacred Groves & Clan Guardians)" oninput="updateOutlineTitle(${index}, this.value)">
          <button type="button" class="btn btn-ghost btn-sm" onclick="removeOutlineSection(${index})" title="Remove Section" style="color: var(--accent-rose); padding: 4px 6px;">✕</button>
        </div>
      </div>
    `;
  });
  container.innerHTML = html;
}

function addOutlineSection() {
  currentOutline.push({ title: '', subheadings: [] });
  renderOutlineBuilder();
}

function updateOutlineTitle(index, val) {
  if (currentOutline[index]) {
    currentOutline[index].title = val;
  }
}

function removeOutlineSection(index) {
  currentOutline.splice(index, 1);
  renderOutlineBuilder();
}

