function getDefaultFluxPrompt() {
  // 1. If an AI image prompt exists from generation, use it
  if (currentImagePrompts && currentImagePrompts.length > 0 && currentImagePrompts[0]?.prompt) {
    return currentImagePrompts[0].prompt;
  }

  // 2. Otherwise derive from Article Title or Topic
  const titleField = document.getElementById('article_title');
  const topicField = document.getElementById('article_topic');
  const regionField = document.getElementById('article_region');

  let subject = (titleField && titleField.value && titleField.value !== 'Untitled Draft') ? titleField.value.trim() : '';
  if (!subject && topicField && topicField.value) {
    subject = topicField.value.trim();
  }
  if (!subject) return '';

  subject = subject.replace(/^#\s*/, '').replace(/\[|\]/g, '').trim();
  const region = (regionField && regionField.value) ? regionField.value.trim() : '';

  // If topic relates to an artifact/shrine/carving, default to a museum macro still life to avoid uncanny faces
  const isArtifact = /(ikenga|ofo|alusi|oracle|deity|ogwu|shrine|statue|carving|sculpture|mask|mmanwu|bell|staff|tusk)/i.test(subject);
  if (isArtifact) {
    return `Museum-grade tactile macro photograph of authentic antique Igbo ${subject}${region ? ' from ' + region : ''}, carved from seasoned dark Iroko hardwood. Extreme close-up showing deep hand-chiselled cuts, aged patina, dried white kaolin (nzu) powder and red camwood (uhie) in crevices, cowrie shells, resting on a weathered earthen altar in an obi. Sidelit by warm morning window light, 85mm f/2.0 lens, shallow depth of field, strictly NO human beings, NO faces, NO text, 4k photorealism`;
  }

  return `Cinematic 35mm documentary photograph of authentic traditional Igbo cultural setting for ${subject}${region ? ' in ' + region : ''}, golden hour volumetric warm lighting casting long shadows across red clay ground, tactile dust motes, authentic woven Akwete textures, Hasselblad 500C, 80mm lens, f/2.8, Kodachrome film grain, strictly NO text, NO watermarks, NO CGI, 4k resolution`;
}

function ensureFluxPromptPopulated(force = false) {
  const fluxInput = document.getElementById('flux_prompt_input');
  if (!fluxInput) return;

  if (force || !fluxInput.value.trim() || fluxInput.dataset.autoGenerated === 'true') {
    const prompt = getDefaultFluxPrompt();
    if (prompt) {
      fluxInput.value = prompt;
      fluxInput.dataset.autoGenerated = 'true';
    }
  }
}

