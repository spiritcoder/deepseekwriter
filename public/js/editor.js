async function saveArticle(targetStatus = null) {
  const titleField = document.getElementById('article_title');
  const topicField = document.getElementById('article_topic');
  const regionField = document.getElementById('article_region');
  const folderField = document.getElementById('article_folder');
  const statusField = document.getElementById('article_status');
  const summaryField = document.getElementById('executive_summary');
  const markdownField = document.getElementById('markdown_content');
  const btn = document.getElementById('btn-save-article');

  const title = titleField ? titleField.value.trim() : '';
  if (!title) {
    showToast('Please provide an article title', 'error');
    if (titleField) titleField.focus();
    return;
  }

  const folderVal = folderField ? folderField.value : '';
  const payload = {
    title,
    topic: topicField ? topicField.value.trim() : '',
    region: regionField ? regionField.value.trim() : '',
    folder_id: (folderVal && folderVal !== '') ? Number(folderVal) : null,
    status: targetStatus || (statusField ? statusField.value : 'draft'),
    cover_image: currentCoverImage,
    executive_summary: summaryField ? summaryField.value.trim() : '',
    outline: currentOutline,
    content_markdown: markdownField ? markdownField.value : '',
    citations: currentSearchResults,
    image_prompts: currentImagePrompts,
    reasoning_log: currentReasoning
  };

  const isUpdating = !!currentArticleId;
  const endpoint = isUpdating ? `/api/articles/${currentArticleId}` : '/api/articles';
  const method = isUpdating ? 'PUT' : 'POST';

  if (btn) {
    btn.disabled = true;
    btn.innerHTML = `<span class="spinner"></span> Saving...`;
  }

  try {
    const res = await fetch(endpoint, {
      method,
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify(payload)
    });
    const data = await res.json();
    if (!data.success) throw new Error(data.error);

    currentArticleId = data.article.id;
    if (statusField) {
      statusField.value = data.article.status;
    }
    if (folderField && data.article.folder_id) {
      folderField.value = String(data.article.folder_id);
    }

    showToast(`Saved article as ${data.article.status.toUpperCase()}!`, 'success');

    // Update URL if new article without reloading
    if (!isUpdating) {
      window.history.replaceState({}, '', `/editor/${data.article.id}`);
    }
  } catch (err) {
    showToast('Failed to save article: ' + err.message, 'error');
  } finally {
    if (btn) {
      btn.disabled = false;
      btn.innerHTML = `Save Article`;
    }
  }
}

