function loadPromptToFlux(index) {
  const item = currentImagePrompts[index];
  if (item && item.prompt) {
    const input = document.getElementById('flux_prompt_input');
    if (input) {
      input.value = item.prompt;
      input.dataset.autoGenerated = 'false';
      switchStudioTab('flux');
      closeModal('modal-insert-image');
      showToast('Loaded prompt into Flux Studio!', 'info');
    }
  }
}

async function quickGenerateImage(index, action = 'insert', btnElement = null) {
  const item = currentImagePrompts[index];
  if (!item || !item.prompt) {
    showToast('Prompt not found', 'error');
    return;
  }

  const prompt = item.prompt;
  const titleField = document.getElementById('article_title');
  const slug = titleField ? titleField.value.trim() : 'article';
  const ratio = (item.type === 'cover' || action === 'cover') ? '16:9' : (selectedAspectRatio || '16:9');

  const originalHtml = btnElement ? btnElement.innerHTML : '';
  if (btnElement) {
    btnElement.disabled = true;
    btnElement.innerHTML = `<span class="spinner" style="width: 10px; height: 10px; border-width: 2px;"></span> Generating...`;
  }
  showToast(`Generating image with Flux Worker (${action === 'cover' ? 'Hero Cover' : 'Inline Image'})...`, 'info');

  try {
    const res = await fetch('/api/generate-image', {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({
        prompt,
        aspectRatio: ratio,
        articleSlug: slug
      })
    });

    const data = await res.json();
    if (!data.success) throw new Error(data.error);

    const img = data.image;

    if (action === 'cover') {
      setAsCoverImage(img.url);
      showToast('Generated & set as Article Hero Cover!', 'success');
    } else {
      insertImageToMarkdown(img.url, item.caption || item.prompt);
      showToast('Generated & inserted photo into article!', 'success');
    }

    // Also update flux preview box
    const previewBox = document.getElementById('flux-live-preview');
    if (previewBox) {
      previewBox.innerHTML = `
        <img src="${escapeHtml(img.url)}" class="flux-preview-img" alt="Flux generation">
        <div style="position: absolute; bottom: 8px; right: 8px; display: flex; gap: 6px;">
          <button type="button" class="btn btn-secondary btn-sm" onclick="setAsCoverImage('${escapeHtml(img.url)}')">Set Cover</button>
          <button type="button" class="btn btn-primary btn-sm" onclick="insertImageToMarkdown('${escapeHtml(img.url)}', '${escapeHtml(prompt)}')">Insert Markdown</button>
        </div>
      `;
    }

    closeModal('modal-insert-image');
  } catch (err) {
    showToast('Image generation failed: ' + err.message, 'error');
  } finally {
    if (btnElement) {
      btnElement.disabled = false;
      btnElement.innerHTML = originalHtml;
    }
  }
}

